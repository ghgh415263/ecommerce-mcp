  private static Seed s(
      String name,
      String category,
      int price,
      int stock,
      String brand,
      String description,
      String... options) {
    return new Seed(name, category, price, stock, brand, description, List.of(options));
  }

  private record Seed(
      String name,
      String category,
      int price,
      int stock,
      String brand,
      String description,
      List<String> options) {

    Product toProduct(int no) {
      return new Product(
          name,
          category,
          price,
          stock,
          brand,
          description,
          "https://example.com/images/" + no + ".jpg",
          options);
    }
  }
